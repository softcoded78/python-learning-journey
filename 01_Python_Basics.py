name = 'Icel' # name is a String/str for it is a word
age = 19 # age is whole number so it is an integer/int

print(name) # Icel
print(age) # 19

print(name, type(name)) # Icel <class 'str'>
print(age, type(age)) # 19 <class 'int'>

print(isinstance(name, char)) # False
print(isinstance(name, str)) # True
print(isinstance(age, float)) # False
print(isinstance(age, int)) # True

